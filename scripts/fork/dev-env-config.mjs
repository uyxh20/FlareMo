// Fork-only: the dev wrangler config for scripts/fork/dev-env.mjs. It is
// derived from wrangler.jsonc.example so every resource name carries the
// flaremo-dev prefix, and it is verified with assertConfigDevOnly before use.

import { resolve } from "node:path";
import {
  applyEdits,
  modify,
  parse as parseJsonc,
  printParseErrorCode,
} from "jsonc-parser";
import {
  isPlaceholderDatabaseId,
  resourcesFromConfig,
} from "../provision-cloudflare.mjs";
import { canonicalPublicUrl } from "../write-wrangler-config.mjs";
import {
  ALLOWED_CONFIG_KEYS,
  assertConfigDevOnly,
  DEV_NAME_PREFIX,
  isDevName,
  OUTBOUND_VARS,
  PROD,
} from "./dev-env-guard.mjs";

export const PLACEHOLDER_D1_ID = "00000000-0000-0000-0000-000000000000";
const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export const DEV = Object.freeze({
  workerName: DEV_NAME_PREFIX,
  d1Name: DEV_NAME_PREFIX,
  publicUrl: "https://flaremo-dev.ulysse-ha-19.workers.dev",
  // Different from the example's 1001 so dev traffic never shares counters
  // with the live Worker.
  ratelimitNamespaceId: "2001",
});

const normalize = (value) =>
  String(value ?? "")
    .trim()
    .toLowerCase();

export function parseConfigText(text, label = "wrangler config") {
  const errors = [];
  const config = parseJsonc(text, errors, { allowTrailingComma: true });
  if (errors.length > 0) {
    throw new Error(
      `Cannot parse ${label}: ${errors
        .map((error) => printParseErrorCode(error.error))
        .join(", ")}`,
    );
  }
  return config;
}

function setConfigValue(text, path, value) {
  return applyEdits(
    text,
    modify(text, path, value, {
      formattingOptions: { insertSpaces: true, tabSize: 2, eol: "\n" },
    }),
  );
}

/** flaremo -> flaremo-dev, flaremo-attachments -> flaremo-dev-attachments. */
export function devResourceName(name) {
  const value = String(name ?? "");
  if (value === "flaremo") return DEV_NAME_PREFIX;
  if (value.startsWith("flaremo-") && !isDevName(value)) {
    return `${DEV_NAME_PREFIX}-${value.slice("flaremo-".length)}`;
  }
  throw new Error(
    `Cannot derive a dev name from "${value}": expected "flaremo" or a "flaremo-*" name.`,
  );
}

const DEV_CONFIG_HEADER = [
  "// GENERATED by scripts/fork/dev-env.mjs for the flaremo-dev deployment.",
  "// DEV ONLY: do not deploy this to production and do not edit it by hand;",
  "// `node scripts/fork/dev-env.mjs config` rewrites it from wrangler.jsonc.example.",
  "",
].join("\n");

/**
 * Derive the dev wrangler config from wrangler.jsonc.example.
 *
 * Every resource name gets the flaremo-dev prefix, absolute paths replace the
 * relative ones (the config lives outside the repo root), the public URL points
 * at the dev origin, and outbound email/push vars are forced empty. The result
 * is verified with assertConfigDevOnly before it is returned, and the builder
 * refuses an example it does not fully understand (an unreviewed top-level key
 * could bind to a production resource).
 */
export function buildDevConfig({
  exampleText,
  repoRoot,
  databaseId,
  publicUrl = DEV.publicUrl,
  trustedOrigins = [],
  ratelimitNamespaceId = DEV.ratelimitNamespaceId,
  migrationsDir,
}) {
  const example = parseConfigText(exampleText, "wrangler.jsonc.example");
  const unreviewed = Object.keys(example).filter(
    (key) => !ALLOWED_CONFIG_KEYS.includes(key),
  );
  if (unreviewed.length > 0) {
    throw new Error(
      `wrangler.jsonc.example has top-level keys the dev tooling has not reviewed (${unreviewed.join(", ")}). Review them for production bindings, then add them to ALLOWED_CONFIG_KEYS in scripts/fork/dev-env-guard.mjs.`,
    );
  }
  if (!UUID_RE.test(String(databaseId ?? ""))) {
    throw new Error(
      "A dev D1 database id (UUID) is required; pass --d1-id, set FLAREMO_DEV_D1_ID, or run provision.",
    );
  }
  if (normalize(databaseId) === normalize(PROD.d1Id)) {
    throw new Error("Refusing to use the production D1 id for the dev config.");
  }
  const origin = canonicalPublicUrl(publicUrl);
  if (!origin) throw new Error("A dev public URL is required.");
  if (origin === PROD.publicUrl) {
    throw new Error("The dev public URL must differ from the live URL.");
  }
  const extraOrigins = trustedOrigins
    .map((value) => canonicalPublicUrl(value))
    .filter(Boolean);
  if (!/^[1-9]\d*$/.test(String(ratelimitNamespaceId))) {
    throw new Error("The rate-limit namespace id must be a positive integer.");
  }
  if (String(ratelimitNamespaceId) === PROD.ratelimitNamespaceId) {
    throw new Error(
      `The dev rate-limit namespace id must differ from the example's ${PROD.ratelimitNamespaceId}.`,
    );
  }

  const databases = example.d1_databases ?? [];
  if (databases.length !== 1) {
    throw new Error(
      `Expected exactly one D1 database in wrangler.jsonc.example, found ${databases.length}.`,
    );
  }

  let text = exampleText;
  const set = (path, value) => {
    text = setConfigValue(text, path, value);
  };
  const absolute = (relative) => resolve(repoRoot, relative);

  set(["name"], devResourceName(example.name));
  if (example.$schema) {
    set(["$schema"], absolute("node_modules/wrangler/config-schema.json"));
  }
  if (example.main) set(["main"], absolute(example.main));
  if (example.assets?.directory) {
    set(["assets", "directory"], absolute(example.assets.directory));
  }

  set(
    ["d1_databases", 0, "database_name"],
    devResourceName(databases[0].database_name),
  );
  set(["d1_databases", 0, "database_id"], databaseId);
  set(
    ["d1_databases", 0, "migrations_dir"],
    migrationsDir ?? absolute(databases[0].migrations_dir ?? "migrations"),
  );
  (example.r2_buckets ?? []).forEach((bucket, at) => {
    set(["r2_buckets", at, "bucket_name"], devResourceName(bucket.bucket_name));
  });
  for (const role of ["producers", "consumers"]) {
    (example.queues?.[role] ?? []).forEach((entry, at) => {
      set(["queues", role, at, "queue"], devResourceName(entry.queue));
    });
  }
  (example.vectorize ?? []).forEach((index, at) => {
    set(["vectorize", at, "index_name"], devResourceName(index.index_name));
  });
  (example.ratelimits ?? []).forEach((_limiter, at) => {
    set(
      ["ratelimits", at, "namespace_id"],
      String(Number(ratelimitNamespaceId) + at),
    );
  });

  const exampleVars = example.vars ?? {};
  set(["vars", "FLAREMO_PUBLIC_URL"], origin);
  if ("FLAREMO_TRUSTED_ORIGINS" in exampleVars) {
    set(
      ["vars", "FLAREMO_TRUSTED_ORIGINS"],
      [...new Set([origin, ...extraOrigins])].join(","),
    );
  }
  for (const key of [...OUTBOUND_VARS, "FLAREMO_DEPLOY_REPOSITORY"]) {
    if (key in exampleVars) set(["vars", key], "");
  }

  text = `${DEV_CONFIG_HEADER}${text}`;
  const built = parseConfigText(text, "generated dev config");
  assertConfigDevOnly(built);
  if (JSON.stringify(built).includes("REPLACE_WITH_YOUR")) {
    throw new Error("The generated dev config still contains a placeholder.");
  }
  return text;
}

/** The dev config with migrations_dir pointed at a different directory. */
export function buildMigrationLevelConfig(devConfigText, migrationsDir) {
  const text = setConfigValue(
    devConfigText,
    ["d1_databases", 0, "migrations_dir"],
    migrationsDir,
  );
  assertConfigDevOnly(parseConfigText(text, "migration-level config"));
  return text;
}

export function describeConfig(config) {
  const resources = resourcesFromConfig(config);
  return [
    ["worker", resources.workerName],
    [
      "D1",
      `${resources.databaseName} (${
        isPlaceholderDatabaseId(resources.databaseId)
          ? "placeholder id: run provision"
          : resources.databaseId
      })`,
    ],
    ["R2", resources.bucketName],
    ["queues", resources.queues.join(", ")],
    [
      "vectorize",
      `${resources.indexes.join(", ")} (${resources.dimensions} dims, ${resources.metric})`,
    ],
    ["public url", resources.publicUrl],
    [
      "rate limit",
      (config.ratelimits ?? [])
        .map((limiter) => `${limiter.name}=${limiter.namespace_id}`)
        .join(", "),
    ],
  ];
}
